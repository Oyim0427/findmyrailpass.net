import fs from 'node:fs';

const SOURCE_FILE = 'src/data/domesticPassDirectory.ts';
const REPORT_FILE = 'reports/directory-link-health.json';
const OUTPUT_FILE = 'src/data/directoryLinkHealth.ts';
const content = fs.readFileSync(SOURCE_FILE, 'utf8');
const urls = [...new Set([...content.matchAll(/"relatedUrl":\s*"([^"]+)"/g)].map(match => match[1]))];

async function check(url) {
  const started = Date.now();
  try {
    let response = await fetch(url, { method: 'HEAD', redirect: 'follow', signal: AbortSignal.timeout(12000) });
    if ([400, 403, 405, 406, 429].includes(response.status)) {
      response = await fetch(url, { method: 'GET', redirect: 'follow', signal: AbortSignal.timeout(12000) });
    }
    return { url, reachable: response.ok, status: response.status, finalUrl: response.url, latencyMs: Date.now() - started };
  } catch (error) {
    return { url, reachable: false, status: 0, error: error instanceof Error ? error.message : String(error), latencyMs: Date.now() - started };
  }
}

async function mapWithConcurrency(items, concurrency, mapper) {
  const results = new Array(items.length);
  let cursor = 0;
  await Promise.all(Array.from({ length: concurrency }, async () => {
    while (cursor < items.length) {
      const index = cursor++;
      results[index] = await mapper(items[index]);
    }
  }));
  return results;
}

const results = await mapWithConcurrency(urls, 12, check);
const reachable = results.filter(result => result.reachable);
const report = {
  checkedAt: new Date().toISOString(),
  urlCount: urls.length,
  reachable: reachable.length,
  unreachable: results.length - reachable.length,
  results,
};
fs.mkdirSync('reports', { recursive: true });
fs.writeFileSync(REPORT_FILE, `${JSON.stringify(report, null, 2)}\n`);
const unreachableUrls = results.filter(result => !result.reachable).map(result => result.url).sort();
fs.writeFileSync(OUTPUT_FILE, `// Generated by scripts/check-directory-links.mjs.\nexport const DIRECTORY_LINKS_CHECKED_AT = ${JSON.stringify(report.checkedAt)};\nexport const UNREACHABLE_DIRECTORY_URLS = ${JSON.stringify(unreachableUrls, null, 2)} as const;\n`);
console.log(`Directory related URLs: ${report.urlCount} checked, ${report.reachable} reachable, ${report.unreachable} unreachable. Report: ${REPORT_FILE}`);
